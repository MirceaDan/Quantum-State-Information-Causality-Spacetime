"""Historical geometry reconstruction from geometry-coupled relational observables.

This module implements the "reverse Theseus" experiment described in the
attached specification: it asks whether later-state quantum-information and
causal observables, generated by a *geometry-coupled* relational process
(``historical_process.py``), carry enough information to reconstruct a hidden
historical geometry -- up to observational equivalence, not exact microscopic
recovery.

The existing independent-observable experiment in ``geometry_reconstruction.py``
remains a valid null baseline (EXP-HIST-NULL-001): it shows that observables
generated *independently* of geometry do not reconstruct it. This module adds
the geometry-coupled positive-control construction (EXP-HIST-COUPLED-001), an
information-retention sweep (EXP-HIST-RETENTION-001), an identifiability probe
(EXP-HIST-IDENT-001), and a randomized control on the coupled observables
(EXP-HIST-RANDOM-001).

No metric component, coordinate, or world/time label is ever exposed to the
reconstruction fit; ground truth is used only for evaluation after fitting.
Q and Delta_munu remain exactly zero throughout (see ``speculative_gate``).
"""

