@dataclass(frozen=True)
class HistoricalObservables:
    """Later-state observable bundle O_t1; never contains coordinates or metric data."""

    pairwise_information: np.ndarray
    multipartite_information: dict[tuple[int, int, int], float]
    intervention_tensor: np.ndarray
    causal_estimate: np.ndarray
    event_count: int
    labels: tuple[str, ...] = (
        "pairwise_mutual_information",
        "multipartite_information",
        "intervention_response_tensor",
        "causal_estimate",
    )

    def flatten(self) -> np.ndarray:
        upper = np.triu_indices(self.event_count, k=1)
        parts = [self.pairwise_information[upper]]
        if self.multipartite_information:
            parts.append(np.array(list(self.multipartite_information.values()), dtype=float))
        parts.append(self.intervention_tensor.ravel())
        return np.concatenate(parts)


def _estimate_causal_matrix(tensor: np.ndarray, threshold: float = 0.02) -> np.ndarray:
    """Derive a causal-direction estimate from observed responses only (no ground truth)."""
    count = tensor.shape[0]
    matrix = np.zeros((count, count), dtype=bool)
    for source in range(count):
        for target in range(count):
            if source == target:
                continue
            matrix[source, target] = tensor[source, target] > threshold and tensor[source, target] >= tensor[target, source]
    return matrix


def build_historical_observables(
    process: HistoricalProcessResult,
    world: GroundTruthWorld,
    intervention_operator: np.ndarray | None = None,
    intervention_label: str = "X",
) -> HistoricalObservables:
    """Build O_t1 from a process result, replaying the SAME control variant for the causal probe."""
    engine = InformationCausalityEngine(process.system)
    pairwise = engine.mutual_information_matrix()
    multipartite = engine.multipartite_information_triples() if process.event_count >= 3 else {}
    causal_response = historical_intervention_response(
        world,
        process.retention,
        process.length_scale,
        intervention_operator=intervention_operator,
        intervention_label=intervention_label,
        force_zero_coupling=(process.control_label == ZERO_COUPLING),
        interval_permutation=process.interval_permutation or None,
        schedule=process.schedule if process.schedule else None,
    )
    causal_estimate = _estimate_causal_matrix(causal_response.tensor)
    tensor_3d = causal_response.tensor[:, :, np.newaxis]
    return HistoricalObservables(pairwise, multipartite, tensor_3d, causal_estimate, process.event_count)


def randomize_historical_observables(observables: HistoricalObservables, seed: int) -> HistoricalObservables:
    """Randomized/null control: permute observables to preserve marginals but destroy pairing."""
    rng = np.random.default_rng(seed)
    count = observables.event_count
    upper = np.triu_indices(count, k=1)
    values = observables.pairwise_information[upper].copy()
    rng.shuffle(values)
    randomized_information = np.zeros_like(observables.pairwise_information)
    randomized_information[upper] = values
    randomized_information[(upper[1], upper[0])] = values

    randomized_multipartite = dict(observables.multipartite_information)
    if randomized_multipartite:
        keys = list(randomized_multipartite.keys())
        shuffled_values = np.array(list(randomized_multipartite.values()), dtype=float)
        rng.shuffle(shuffled_values)
        randomized_multipartite = dict(zip(keys, shuffled_values))

    order = rng.permutation(count)
    randomized_tensor = observables.intervention_tensor[order][:, order]
    randomized_causal = observables.causal_estimate[order][:, order]
    return HistoricalObservables(randomized_information, randomized_multipartite, randomized_tensor, randomized_causal, count)


